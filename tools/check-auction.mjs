import fs from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {EMPTY, validFeed, freshness, itemState, filteredItems, marketIndex, escape} from '../auction/model.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'auction/catalog.json'),'utf8'));
assert.equal(catalog.items.length,22616);
assert.equal(new Set(catalog.items.map(x=>x[0])).size,22616);
const cats={3:['Weapons','Sword'],46:['Others','Misc.'],64:['Others','Misc.2']};
const items=[[1,'Alpha',3,1,10,''],[2,'Beta',46,12,0,''],[3,'Never',0,99,0,'NOAUCTION'],[4,'Outside',3,1,20,''],[5,'Gamma',64,12,0,''],[6,'Unverified',255,1,0,'Unverified category']];
const feed={version:1,observedAt:1000,service:'running',pool:[1,2],profiles:[{name:'Market',items:[2]}],market:{1:[[2,1,100,990,3,90],EMPTY],2:[EMPTY,[3,4,1200,995,8,1100]]},history:{1:[[[990,100]],[]],2:[[],[[995,1200]]]}};
assert(validFeed(feed));
assert(!validFeed({...feed,version:2}));
assert(!validFeed({...feed,market:{1:[[1,-2,3,4,5,6],EMPTY]}}));
assert.equal(freshness(feed,1001),'running');
assert.equal(freshness(feed,1361),'stale');
assert.equal(freshness({...feed,service:'offline'},1001),'offline');
assert.equal(freshness(feed,900),'stale');
assert.equal(freshness(null),'error');
assert.equal(itemState(items[0],feed,0),'available');
assert.equal(itemState(items[0],feed,1),'empty');
assert.equal(itemState(items[1],feed,1),'available');
assert.equal(itemState(items[2],feed,0),'never');
assert.equal(itemState(items[3],feed,0),'outside');
assert.equal(itemState(items[5],feed,0),'unverified');
assert.equal(itemState(items[0],null,0),'unknown');
const filter=options=>filteredItems(items,cats,feed,options).map(x=>x[0]);
assert.deepEqual(filter({}),[1,2,5,4]);
assert.deepEqual(filter({category:'Weapons'}),[1,4]);
assert.deepEqual(filter({category:'Others / Misc.'}),[2]);
assert.deepEqual(filter({status:'available'}),[1]);
assert.deepEqual(filter({status:'available',mode:1}),[2]);
assert.deepEqual(filter({status:'never'}),[3]);
assert.deepEqual(filter({category:'never',status:'every'}),[3,6]);
assert.deepEqual(filter({status:'rotation'}),[2]);
assert.deepEqual(filter({status:'outside'}),[5,4]);
assert.deepEqual(filter({status:'sold',mode:1}),[2]);
assert.deepEqual(filter({query:'weapons alpha'}),[1]);
assert.deepEqual(filter({query:'2'}),[2,5]);
assert.deepEqual(filter({sort:'stock'}),[1,2,5,4]);
assert.deepEqual(filter({sort:'level'}),[2,5,1,4]);
assert.equal(marketIndex(feed).rotation.size,1);
assert.equal(escape('<script>"&'), '&lt;script&gt;&quot;&amp;');
const seal=catalog.items.find(x=>x[0]===1127);
assert.equal(itemState(seal,feed,0),'never');
assert.equal(seal[5],'NOAUCTION');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.equal((html.match(/href="auction\/index.html"/g)||[]).length,1);
assert(html.indexOf('href="auction/index.html"')>html.indexOf('<h2>Items & Crafting</h2>'));
console.log('PASS: actual 22,616-item catalog; native exclusions, hierarchy boundaries, singles/stacks, quantities, filters, sorting, stale/offline, references and isolated home navigation.');
